#!/usr/bin/env bash
# Final verification of the public decode entry points (called by scripts/verify.sh):
#  1. the Lean-library change patches/aeneas-lean-tostr-kernel-proof.patch is what is applied, and its
#     recorded upstream tests/lean validation passed;
#  2. fresh extended extraction (extract-api.sh) with Engine::decode and Engine::decode_vec;
#  3. consistency: every item of the main model proof/DecodeModel occurs identically in the extended
#     model, except the Engine record and its two impls, which differ only by the two added fields;
#  4. proof/DecodeProof.lean re-checked unchanged on the extended model (DecodeApiBase, generated by
#     renaming the namespace), then DecodeApiProof.lean (decode_equiv, decode_vec_equiv and their
#     generic-input forms decode_default_equiv, decode_vec_default_equiv), with axiom audit;
#  5. negative controls for the new theorems (check-negative-api.sh).
set -euo pipefail
source "$(dirname "$0")/../scripts/env.sh"
H=$HELDOUT
F=$H/final-verification
cd "$H"
log=$F/logs/verify-final.log
: > "$log"
say() { echo "$*" | tee -a "$log"; }
T=$H/tool-validation/trees/aeneas-final
git -C "$T" diff backends/lean/Aeneas/Std/String.lean | cmp - patches/aeneas-lean-tostr-kernel-proof.patch
COMPARE_ONLY=1 bash "$F/run-lean-tests-tostr.sh" | tee -a "$log"
grep -q '^extract-exit=0$' "$F/logs/extract-lean-std-tostr.log"
git -C "$T" diff --quiet -- src/extract/ExtractBuiltinLean.ml
say "toStr library change: applied as recorded; upstream tests/lean and ExtractBuiltinLean.ml checks OK"

bash "$F/extract-api.sh" base64-decode-pairs DecodeApiModel > "$F/logs/extract-api.log" 2>&1
say "fresh extended extraction OK"

python3 - "$H" <<'PY' | tee -a "$log"
import re, sys
from pathlib import Path
H = Path(sys.argv[1])
A = (H / 'proof/DecodeModel/DecodeModel.lean').read_text()
B = (H / 'final-verification/lean/DecodeApiModel/DecodeApiModel.lean').read_text().replace('DecodeApiModel', 'DecodeModel')
def items(text):
    out = {}
    for m in re.finditer(r'\n(def|structure|inductive|axiom|impl_def)\s*\n?\s*(\S+)(.*?)(?=\n\n)', text, re.S):
        out[(m.group(1), m.group(2))] = ' '.join(m.group(3).split())
    return out
IA, IB = items(A), items(B)
changed = {('structure', 'engine.Engine'),
  ('impl_def', 'engine.general_purpose.GeneralPurpose.Insts.Base64EngineEngineGeneralPurposeConfigGeneralPurposeEstimate'),
  ('impl_def', 'engine.general_purpose.ref_engine.RefGeneralPurpose.Insts.Base64EngineEngineGeneralPurposeConfigGeneralPurposeEstimate')}
for k, body in IA.items():
    assert k in IB, f'missing in extended model: {k}'
    if k in changed:
        # remove the two added fields (`decode_to_vec`, `decode_vec`), which precede `decode_slice`
        stripped = re.sub(r'decode_to_vec :=? .*? (?=decode_vec :=? )', '', IB[k])
        stripped = re.sub(r'decode_vec :=? .*? (?=decode_slice :=? )', '', stripped)
        assert stripped == body, f'{k} differs beyond the added fields'
    else:
        assert body == IB[k], f'item differs: {k}'
new = sorted(k[1] for k in IB if k not in IA)
print(f'model consistency OK: all {len(IA)} items of DecodeModel occur in DecodeApiModel; '
      f'{len(IA) - 3} identical, 3 differ only by the added decode_to_vec/decode_vec fields; {len(new)} new items')
for n in new: print('   new:', n)
PY

sed 's/^import DecodeModel\.DecodeModel$/import DecodeApiModel.DecodeApiModel/; s/^open DecodeModel$/open DecodeApiModel/; s/DecodeProof/DecodeApiBase/g' \
  proof/DecodeProof.lean > "$F/lean/DecodeApiBase.lean"
(cd proof && taskset -c 64-79 lake build DecodeApiProof) > "$F/logs/verify-api-lean.log" 2>&1
if grep -nE '\b(sorry|admit|native_decide|bv_decide|implemented_by)\b|^axiom|decide \+native' "$F/lean/DecodeApiProof.lean"; then
  say "FAIL: forbidden construct in proof"; exit 1; fi
if grep -nE '\bsorry\b' "$F/lean/DecodeApiModel/DecodeApiModel.lean"; then say "FAIL: sorry in model"; exit 1; fi
if grep -nE 'sorryAx|Lean.ofReduceBool|Lean.trustCompiler|_native' "$F/logs/verify-api-lean.log"; then say "FAIL: axiom audit"; exit 1; fi
python3 - "$F/logs/verify-api-lean.log" <<'PY' | tee -a "$log"
import re, sys
from pathlib import Path
log = Path(sys.argv[1]).read_text()
audits = {m.group(1): {x.strip() for x in m.group(2).split(',')}
          for m in re.finditer(r"'(?:DecodeApiBase|DecodeApiProof)\.(\w+)' depends on axioms: \[(.*?)\]", log, re.S)}
std = {'propext', 'Classical.choice', 'Quot.sound'}
shared = {'engine.general_purpose.decode_suffix.decode_suffix', 'engine.general_purpose.encode_helper',
          'Shared0T.Insts.CoreConvertAsRef.as_ref', 'Slice.Insts.CoreConvertAsRefSlice.as_ref',
          'core.result.Result.map'}
vec = {'alloc.vec.Vec.truncate', 'alloc.vec.Vec.as_mut_slice'}
allowed = std | {'core.fmt.Formatter'} | shared | vec
assert audits['pairs_spec'] <= std, audits['pairs_spec']
for k in ['chunk8_pairs_eq', 'chunk4_pairs_eq', 'decode_complete_quads_equiv']:
    assert audits[k] <= std | {'core.fmt.Formatter'}, (k, audits[k])
for k in ['decode_slice_equiv', 'decode_equiv', 'decode_vec_equiv', 'decode_default_equiv', 'decode_vec_default_equiv']:
    assert audits[k] <= allowed, (k, audits[k] - allowed)
for k in ['decode_equiv', 'decode_vec_equiv', 'decode_default_equiv', 'decode_vec_default_equiv']:
    print(f'axiom audit OK: {k}: {sorted(audits[k])}')
PY
say "extended proof build (DecodeApiBase + DecodeApiProof) + axiom audit OK"

bash "$F/check-negative-api.sh" > "$F/logs/negative-control-api.log" 2>&1
grep '^PASS' "$F/logs/negative-control-api.log" | tee -a "$log"
say "PASS: final verification (public Engine::decode and Engine::decode_vec equivalence)"

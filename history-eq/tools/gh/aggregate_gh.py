#!/usr/bin/env python3
"""Merge the selected-optimization ledgers with the GitHub-enabled per-case results
(history-eq/gh/results/<repo>/<commit>.json) and render the four-category report.

Previously `checked` ledger entries keep their verdict; every other entry takes the
gh result if one exists, otherwise it stays as in the ledger (and is counted as
`not processed`)."""
import glob, json, os
from collections import Counter

HE = "/srv/home/hantaolou/code/veriop/history-eq"
RES = f"{HE}/results"
GH = f"{HE}/gh/results"
CAT = {"NOT_EQUIV": "unequal", "EQUIV": "equal", "REFINES": "equal", "EQUIV_UNDER_PRECOND": "equal",
       "EQUIV_BOUNDED": "unverified", "EQUIV_PARTIAL": "unverified", "REFINES_PARTIAL": "unverified",
       "UNKNOWN": "unverified", "UNSUPPORTED": "unsupported"}
ORDER = ["zstd", "xxHash", "aws-lc", "fast_float", "simdjson", "openssl", "s2n-bignum", "SymCrypt",
         "rust-base64", "regex", "v4-core", "openzeppelin-contracts", "hacl-star", "everparse",
         "aws-encryption-sdk", "aws-database-encryption-sdk-dynamodb", "compress", "scion",
         "RoaringBitmap", "netty", "evm-semantics", "kontrol", "llama.cpp", "cutlass", "flash-attention"]


def ledgers():
    for f in glob.glob(f"{RES}/*-optimization-sample.json"):
        d = json.load(open(f))
        yield d["repo"], os.path.basename(f), d["entries"]
    d = json.load(open(f"{RES}/SymCrypt-partial.json"))
    yield "SymCrypt", "SymCrypt-partial.json", [
        {"commit": c["commit"], "verdict": c.get("commit_verdict") or c.get("verdict") or "UNSUPPORTED",
         "checker_status": c.get("checker_status")} for c in d["commits"]]


def gh_result(repo, commit):
    p = f"{GH}/{repo}/{commit}.json"
    if not os.path.exists(p):
        hits = glob.glob(f"{GH}/{repo}/{commit[:8]}*.json")
        p = hits[0] if len(hits) == 1 else None
    return json.load(open(p)) if p else None


def main():
    rows, merged = [], {}
    for repo, src, entries in ledgers():
        cnt, sub, reasons, out = Counter(), Counter(), Counter(), []
        for e in entries:
            r = None if e.get("checker_status") == "checked" else gh_result(repo, e["commit"])
            if r:
                v, origin, ran = r["verdict"], "gh", bool(r.get("checker_ran"))
            else:
                v = e["verdict"]
                origin = "prior-checked" if e.get("checker_status") == "checked" else "not-processed"
                ran = e.get("checker_status") == "checked"
            assert v in CAT, (repo, e["commit"], v)
            c = CAT[v]
            cnt[c] += 1
            cnt["ran" if ran else "not_ran"] += 1
            cnt[origin] += 1
            if v in ("EQUIV_BOUNDED", "EQUIV_PARTIAL", "REFINES_PARTIAL"): sub["partial"] += 1
            if v == "NOT_EQUIV" and r and r.get("not_equiv_level") == "public-api": sub["neq_public"] += 1
            if v == "UNSUPPORTED" and r: reasons[r.get("unsupported_reason") or "unspecified"] += 1
            out.append({"commit": e["commit"], "verdict": v, "category": c, "origin": origin,
                        "checker_ran": ran, "checker": (r or {}).get("checker") or e.get("checker_target"),
                        "scope": (r or {}).get("scope") or e.get("coverage"),
                        "evidence": (r or {}).get("evidence_dir") or e.get("evidence")})
        rows.append({"repo": repo, "ledger": src, "n": len(entries), **cnt, **sub,
                     "top_unsupported": reasons.most_common(3)})
        merged[repo] = out
    rows.sort(key=lambda r: ORDER.index(r["repo"]) if r["repo"] in ORDER else 99)
    json.dump({"rows": rows, "entries": merged}, open(f"{RES}/GH_FOUR_CATEGORY_STATUS.json", "w"), indent=1)
    T = Counter()
    lines = ["| Repo | Samples | Verified unequal | Verified equal/refinement | Unverified | Unsupported "
             "| (partial/bounded in unverified) | Checker ran | Not yet processed |",
             "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for r in rows:
        for k in ("n", "unequal", "equal", "unverified", "unsupported", "partial", "ran", "not-processed"):
            T[k] += r.get(k, 0)
        lines.append(f"| {r['repo']} | {r['n']} | {r.get('unequal',0)} | {r.get('equal',0)} | "
                     f"{r.get('unverified',0)} | {r.get('unsupported',0)} | {r.get('partial',0)} | "
                     f"{r.get('ran',0)} | {r.get('not-processed',0)} |")
    lines.append(f"| **Total** | {T['n']} | {T['unequal']} | {T['equal']} | {T['unverified']} | "
                 f"{T['unsupported']} | {T['partial']} | {T['ran']} | {T['not-processed']} |")
    md = ("# Four-category results after the GitHub-enabled run\n\n"
          "Generated by `history-eq/tools/gh/aggregate_gh.py`. Protocol: `history-eq/tools/gh/PROTOCOL.md`. "
          "Equal = every changed executable definition proved (EQUIV/REFINES/EQUIV_UNDER_PRECOND) in the "
          "recorded configuration; bounded/partial proofs count as unverified.\n\n" + "\n".join(lines) + "\n")
    open(f"{RES}/GH_FOUR_CATEGORY_STATUS.md", "w").write(md)
    print(md)


if __name__ == "__main__":
    main()

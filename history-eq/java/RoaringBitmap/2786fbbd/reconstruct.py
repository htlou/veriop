#!/usr/bin/env python3
"""Extract the exact historical changed methods into a runnable Java witness."""

from pathlib import Path
import subprocess

here = Path(__file__).resolve().parent
root = here.parents[3]
repo = root / "benchmarks/repos/RoaringBitmap"
commit = "2786fbbd"
path = "RoaringBitmap/src/main/java/org/roaringbitmap/RunContainer.java"


def historical(rev: str, source_path: str = path) -> str:
    return subprocess.check_output(
        ["git", "-C", str(repo), "show", f"{rev}:{source_path}"]
    ).decode()


def method(src: str, signature: str) -> str:
    start = src.index(signature)
    open_brace = src.index("{", start)
    depth = 0
    for i in range(open_brace, len(src)):
        if src[i] == "{":
            depth += 1
        elif src[i] == "}":
            depth -= 1
            if depth == 0:
                return src[start : i + 1]
    raise AssertionError(signature)


old = historical(commit + "^")
new = historical(commit)
for label, src in (("old", old), ("new", new)):
    (here / f"RunContainer.{label}.txt").write_text(src)

diff = subprocess.check_output(
    ["git", "-C", str(repo), "diff", commit + "^", commit, "--", path]
)
(here / "runcontainer.diff").write_bytes(diff)
production_paths = [
    path,
    "RoaringBitmap/src/main/java/org/roaringbitmap/buffer/MappeableRunContainer.java",
]
changed_paths = subprocess.check_output(
    ["git", "-C", str(repo), "diff", "--name-only", commit + "^", commit]
).decode().splitlines()
assert changed_paths == production_paths, changed_paths
(here / "production.diff").write_bytes(
    subprocess.check_output(["git", "-C", str(repo), "diff", commit + "^", commit])
)

# Establish that the witness is reachable through unchanged public production code.
container_path = "RoaringBitmap/src/main/java/org/roaringbitmap/Container.java"
before_container = historical(commit + "^", container_path)
after_container = historical(commit, container_path)
dispatch_sig = "public boolean contains(Container subset)"
assert method(before_container, dispatch_sig) == method(after_container, dispatch_sig)
assert "contains((BitmapContainer)subset)" in method(before_container, dispatch_sig)
bitmap_path = "RoaringBitmap/src/main/java/org/roaringbitmap/BitmapContainer.java"
before_bitmap = historical(commit + "^", bitmap_path)
after_bitmap = historical(commit, bitmap_path)
bitmap_constructor = "public BitmapContainer()"
assert method(before_bitmap, bitmap_constructor) == method(after_bitmap, bitmap_constructor)
assert "this.cardinality = 0" in method(before_bitmap, bitmap_constructor)
assert "this.bitmap = new long[MAX_CAPACITY / 64]" in method(before_bitmap, bitmap_constructor)
assert "MAX_CAPACITY = 1 << 16" in before_bitmap or "MAX_CAPACITY = 1<<16" in before_bitmap

run_constructor = "public RunContainer(final int firstOfRun, final int lastOfRun)"
assert method(old, run_constructor) == method(new, run_constructor)
assert "this.nbrruns = 1" in method(old, run_constructor)
assert "(char) firstOfRun" in method(old, run_constructor)
assert "(char) (lastOfRun - 1 - firstOfRun)" in method(old, run_constructor)

signature = "protected boolean contains(BitmapContainer bitmapContainer)"
old_method = method(old, signature)
new_method = method(new, signature)
assert old_method != new_method

helpers = {
    name: method(old, sig)
    for name, sig in {
        "cardinality": "public int getCardinality()",
        "runs": "public int numberOfRuns()",
        "value": "public char getValue(int index)",
        "length": "public char getLength(int index)",
    }.items()
}
for name, sig in {
    "cardinality": "public int getCardinality()",
    "runs": "public int numberOfRuns()",
    "value": "public char getValue(int index)",
    "length": "public char getLength(int index)",
}.items():
    assert helpers[name] == method(new, sig), name


def run_class(label: str, body: str) -> str:
    name = "RunOld" if label == "old" else "RunNew"
    return f"""
  static final class {name} {{
    int nbrruns = 1;
    char[] valueslength = new char[] {{100, 0}};
    {helpers['cardinality']}
    {helpers['runs']}
    {helpers['value']}
    {helpers['length']}
    {body}
  }}
"""


witness = f"""// Generated by reconstruct.py from exact historical method bodies.
public final class ExtractedContainsWitness {{
  static final class BitmapContainer {{
    final long[] bitmap = new long[1024];
    int getCardinality() {{ return 0; }}
  }}
  {run_class('old', old_method)}
  {run_class('new', new_method)}
  public static void main(String[] args) {{
    BitmapContainer empty = new BitmapContainer();
    boolean before = new RunOld().contains(empty);
    boolean after = new RunNew().contains(empty);
    System.out.println("trailingZeros0=" + Long.numberOfTrailingZeros(0L));
    System.out.println("old=" + before + " new=" + after);
    if (!before || after) throw new AssertionError("expected historical mismatch");
  }}
}}
"""
(here / "ExtractedContainsWitness.java").write_text(witness)
print("Exact changed methods, unchanged helpers, constructors, and public dispatch checked")
